-- Skema database PSB Kuttab Imam Al-Ghazali (PostgreSQL / Supabase)
-- Waktu disimpan sebagai teks UTC 'YYYY-MM-DD HH24:MI:SS' agar konsisten dengan frontend.

CREATE OR REPLACE FUNCTION now_txt() RETURNS text LANGUAGE sql STABLE
  SET search_path = ''
  AS $$ SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS') $$;

CREATE OR REPLACE FUNCTION ts_txt(delta interval) RETURNS text LANGUAGE sql STABLE
  SET search_path = ''
  AS $$ SELECT to_char((now() AT TIME ZONE 'utc') + delta, 'YYYY-MM-DD HH24:MI:SS') $$;

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  phone text,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'parent' CHECK (role IN ('parent','panitia','admin')),
  active integer NOT NULL DEFAULT 1,
  last_login_at text,
  created_at text NOT NULL DEFAULT now_txt()
);

CREATE TABLE IF NOT EXISTS programs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  tagline text,
  description text,
  age_min integer NOT NULL,
  age_max integer NOT NULL,
  quota integer NOT NULL DEFAULT 0,
  gender_policy text NOT NULL DEFAULT 'campur',
  highlights text NOT NULL DEFAULT '[]',
  monthly_fee integer NOT NULL DEFAULT 0,
  entry_fee integer NOT NULL DEFAULT 0,
  active integer NOT NULL DEFAULT 1,
  sort integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS waves (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  academic_year text NOT NULL,
  start_date text NOT NULL,
  end_date text NOT NULL,
  observation_date text,
  announcement_date text,
  registration_fee integer NOT NULL DEFAULT 0,
  quota integer NOT NULL DEFAULT 0,
  active integer NOT NULL DEFAULT 1,
  notes text
);

CREATE TABLE IF NOT EXISTS applications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reg_number text UNIQUE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  wave_id integer REFERENCES waves(id),
  program_id integer REFERENCES programs(id),
  status text NOT NULL DEFAULT 'draft',
  full_name text, nickname text, gender text, birth_place text, birth_date text,
  nik text, kk_number text, child_order integer, siblings integer,
  address text, city text, province text, postal_code text,
  previous_school text, quran_ability text, memorization text,
  blood_type text, height_cm integer, weight_kg integer, allergies text,
  medical_history text, special_needs text,
  father text NOT NULL DEFAULT '{}',
  mother text NOT NULL DEFAULT '{}',
  guardian text NOT NULL DEFAULT '{}',
  motivation text, info_source text, commitments text NOT NULL DEFAULT '{}',
  observation_at text, observation_place text, observer text, observation_note text,
  score_total double precision, decision_note text,
  submitted_at text, decided_at text,
  created_at text NOT NULL DEFAULT now_txt(),
  updated_at text NOT NULL DEFAULT now_txt()
);
CREATE INDEX IF NOT EXISTS idx_app_user ON applications(user_id);
CREATE INDEX IF NOT EXISTS idx_app_status ON applications(status);
CREATE INDEX IF NOT EXISTS idx_app_program ON applications(program_id);
CREATE INDEX IF NOT EXISTS idx_app_wave ON applications(wave_id);

CREATE TABLE IF NOT EXISTS documents (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id integer NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  type text NOT NULL,
  filename text NOT NULL,
  original_name text,
  mime text, size integer,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','valid','invalid')),
  note text,
  uploaded_at text NOT NULL DEFAULT now_txt(),
  UNIQUE(application_id, type)
);

CREATE TABLE IF NOT EXISTS payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id integer NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('registration','reregistration')),
  amount integer NOT NULL,
  payer_name text, bank_name text, paid_at text,
  proof_filename text, proof_mime text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  note text, verified_by integer REFERENCES users(id) ON DELETE SET NULL, verified_at text,
  created_at text NOT NULL DEFAULT now_txt()
);
CREATE INDEX IF NOT EXISTS idx_pay_app ON payments(application_id);
CREATE INDEX IF NOT EXISTS idx_pay_verified_by ON payments(verified_by);

CREATE TABLE IF NOT EXISTS assessments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id integer NOT NULL UNIQUE REFERENCES applications(id) ON DELETE CASCADE,
  scores text NOT NULL DEFAULT '{}',
  total double precision,
  recommendation text,
  note text,
  assessor_id integer REFERENCES users(id) ON DELETE SET NULL,
  updated_at text NOT NULL DEFAULT now_txt()
);
CREATE INDEX IF NOT EXISTS idx_asm_assessor ON assessments(assessor_id);

CREATE TABLE IF NOT EXISTS status_history (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id integer NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  status text NOT NULL,
  note text,
  actor_id integer REFERENCES users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT now_txt()
);
CREATE INDEX IF NOT EXISTS idx_hist_app ON status_history(application_id);
CREATE INDEX IF NOT EXISTS idx_hist_actor ON status_history(actor_id);

CREATE TABLE IF NOT EXISTS notifications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title text NOT NULL, body text, link text,
  read_at text,
  created_at text NOT NULL DEFAULT now_txt()
);
CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications(user_id);

CREATE TABLE IF NOT EXISTS announcements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL, body text NOT NULL,
  audience text NOT NULL DEFAULT 'public' CHECK (audience IN ('public','applicants')),
  pinned integer NOT NULL DEFAULT 0,
  published integer NOT NULL DEFAULT 1,
  created_at text NOT NULL DEFAULT now_txt()
);

CREATE TABLE IF NOT EXISTS faqs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question text NOT NULL, answer text NOT NULL,
  sort integer NOT NULL DEFAULT 0, published integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS settings (
  key text PRIMARY KEY,
  value text
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  action text NOT NULL, entity text, entity_id integer, detail text, ip text,
  created_at text NOT NULL DEFAULT now_txt()
);
CREATE INDEX IF NOT EXISTS idx_audit_user ON audit_logs(user_id);

CREATE TABLE IF NOT EXISTS inquiries (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL, phone text, email text, message text NOT NULL,
  handled integer NOT NULL DEFAULT 0,
  created_at text NOT NULL DEFAULT now_txt()
);

